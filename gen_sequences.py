sq3.message(kati, kati, "组装 _protobuf_map_files 列表\n写 maps_list-<product>.txt", kind="self")
sq3.message(kati, rc_bin, "KATI_shell_no_rerun out/release-config \\\n  --product … --release … --variant …\n  --maps-file … --hashfile …")
