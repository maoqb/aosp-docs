sq3.message(kati, soong, "传递 --maps-file、--hashfile\n供 Soong 生成额外产物\n(all_release_configs-*.pb 等)")
sq3.message(soong, kati, "构建完成", kind="return")

sq3.save("/home/mao/code/android-16.0.0_r4/release_config/release_config_flow.drawio")
sq3.save_svg("/home/mao/code/android-16.0.0_r4/release_config/release_config_flow.svg")
print("Saved flow sequence")
